"""
评估指标定义。

业务方原始诉求：回复要「准确、有用、语气好、不能瞎编」。
我们把这四句话映射成 4 个可自动评分的指标，每个指标 1~5 分（整数）。

设计原则：
- 每个指标都有明确的 5/3/1 锚点（rubric），便于 LLM-as-judge 打分保持一致；
- 权重体现业务优先级：「不瞎编」是硬约束（会直接伤害信任/合规），
  「有用」是自动回复的核心价值，「准确」次之，「语气」权重最低；
- groundedness 同时充当硬门槛：若某条回复在「不瞎编」上得 1 分，
  总分封顶 40 并打「疑似编造」红旗。
"""

# 指标权重（合计 = 1.0）
WEIGHTS = {
    "accuracy": 0.25,       # 准确：回复中的事实性陈述是否正确
    "helpfulness": 0.35,    # 有用：是否真正解决用户的具体问题、是否主动服务
    "groundedness": 0.25,   # 不瞎编：是否只陈述可核实信息、不臆造具体事实
    "tone": 0.15,           # 语气好：是否礼貌、有共情、承接用户情绪
}

# 硬门槛：groundedness 得 1 分时总分封顶
GATE_GROUNDEDNESS_SCORE = 1
GATE_CAP_OVERALL = 40

METRICS = {
    "accuracy": {
        "name": "准确性",
        "question": "回复中给出的事实、规则、时效、流程是否正确？",
        "rubric": {
            "5": "所有事实性陈述均正确，无常识/规则错误",
            "3": "主干信息正确，但有 1 处次要含糊或小瑕疵",
            "1": "存在明显事实错误或误导性陈述",
        },
    },
    "helpfulness": {
        "name": "有用性",
        "question": "回复是否真正解决了用户这次的具体问题？是否主动揽办，而不是把用户推去自助？",
        "rubric": {
            "5": "直接针对用户的具体场景给出可执行方案，或主动提出代为查询/办理",
            "3": "给出了通用规则/流程，但没有针对用户的具体情况，也没有主动代查",
            "1": "答非所问，或反复把用户推去「自己看详情页/自己操作」，没有解决问题",
        },
    },
    "groundedness": {
        "name": "不瞎编",
        "question": "回复是否避免了对无法核实的具体事实（具体商品参数、订单状态、额度）做出武断断言？",
        "rubric": {
            "5": "只陈述通用规则或明确需要核实的信息，没有臆造具体事实",
            "3": "对具体事实做了断言，但属于常见政策且与人工参考一致",
            "1": "编造了具体商品参数/订单状态/补偿额度等无法核实的信息",
        },
    },
    "tone": {
        "name": "语气与共情",
        "question": "回复是否礼貌、承接用户情绪？在投诉/焦虑场景下是否有恰当安抚？",
        "rubric": {
            "5": "礼貌且有共情，准确回应用户情绪，无官腔/内部话术",
            "3": "基本礼貌，但偏模板化，情绪承接不足",
            "1": "冷漠、推诿、官腔，或在用户生气时说无关的内部事项",
        },
    },
}

# 1~5 分映射到百分制的说明
SCALE_NOTE = "每个指标按 1~5 整数打分；加权后 ×20 换算为 0~100 分。"


def overall_score(metric_scores: dict) -> float:
    """metric_scores: {metric_key: 1~5}。返回 0~100。"""
    raw = sum(WEIGHTS[k] * metric_scores[k] for k in WEIGHTS)
    overall = raw * 20
    if metric_scores.get("groundedness") == GATE_GROUNDEDNESS_SCORE:
        overall = min(overall, GATE_CAP_OVERALL)
    return round(overall, 1)
